# Populate Windows audio DDC while the commandlet protects pending objects.
# Keep authored sounds, codecs, regular tests and cache inputs unchanged.
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$ProjectPath,
    [Parameter(Mandatory = $true)][string]$ReportsPath
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $false
if (-not $IsWindows) { throw 'Audio DDC warmup requires Windows.' }
$project = (Resolve-Path -LiteralPath $ProjectPath).Path
$projectRoot = Split-Path -Parent $project
$engine = $env:QINGLAN_ENGINE_ROOT
if (-not $engine) { throw 'A prepared engine is required.' }
$editor = Join-Path $engine 'Engine/Binaries/Win64/UnrealEditor-Cmd.exe'
if (-not (Test-Path -LiteralPath $editor -PathType Leaf)) { throw 'Verified editor tools are required.' }
New-Item -ItemType Directory -Force $ReportsPath | Out-Null
$receipt = Join-Path $ReportsPath 'audio-ddc-warmup.json'
if (Test-Path -LiteralPath $receipt) { Remove-Item -LiteralPath $receipt -Force }
$audioRoot = Join-Path $projectRoot 'Content/Qinglan/Audio'
$audio = @(Get-ChildItem -LiteralPath $audioRoot -Recurse -File -Filter 'SW_*.uasset' | Sort-Object FullName)
if ($audio.Count -ne 8) { throw "Expected all eight authored sound waves, found $($audio.Count)." }
$inventory = @($audio | ForEach-Object {
    $relative = [IO.Path]::GetRelativePath((Join-Path $projectRoot 'Content'), $_.FullName).Replace('\', '/')
    @{ path = $relative; object_path = '/Game/' + $relative.Substring(0, $relative.Length - 7) + '.' + $_.BaseName; bytes = $_.Length; sha256 = (Get-FileHash -LiteralPath $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant() }
})
# UE 5.8.3 ProjectCollectionSource.cpp reads local collections from Saved/Collections.
# Collection.cpp accepts version 2 static files; this is disposable CI state.
$collectionName = 'QinglanWindowsAudioDDC_' + [Guid]::NewGuid().ToString('N')
$collectionRoot = Join-Path $projectRoot 'Saved/Collections'
New-Item -ItemType Directory -Force $collectionRoot | Out-Null
$collection = Join-Path $collectionRoot ($collectionName + '.collection')
$header = @(
    'FileVersion:2', 'Type:Static', ('Guid:' + [Guid]::NewGuid().ToString()),
    'ParentGuid:00000000-0000-0000-0000-000000000000', 'IsAutoGenerated:true', ''
)
[IO.File]::WriteAllLines($collection, @($header + @($inventory | ForEach-Object { $_.object_path })), [Text.UTF8Encoding]::new($false))
$passes = @()
try {
    foreach ($pass in @(1, 2)) {
        $engineLog = Join-Path $ReportsPath "audio-ddc-pass-$pass-engine.log"
        $consoleLog = Join-Path $ReportsPath "audio-ddc-pass-$pass.log"
        Write-Host "Preparing all eight Windows sound waves, pass $pass..."
        & $editor $project '-run=DerivedDataCache' '-fill' '-ProjectOnly' `
            "-Collection=$collectionName" '-TargetPlatform=WindowsEditor+Windows' `
            "-abslog=$engineLog" -unattended -nop4 -nosplash -nullrhi -stdout -FullStdOutLogOutput 2>&1 |
            Tee-Object -FilePath $consoleLog
        if ($LASTEXITCODE) { throw "Audio DDC commandlet pass $pass failed ($LASTEXITCODE)." }
        $log = Get-Content -LiteralPath $engineLog -Raw
        if ($log -notmatch 'LogDerivedDataCacheCommandlet: Display: BeginCacheTime=') { throw 'DDC commandlet did not finish caching/quiescence.' }
        if ($log -match '(?im)Log[^\r\n]*: (Error|Fatal):|Timed out[^\r\n]*finish caching|Could not find audio format to cook|Error loading|Fatal error|Unhandled Exception') {
            throw "Audio DDC pass $pass reported a cache/load failure."
        }
        foreach ($item in $inventory) {
            $package = $item.object_path.Split('.')[0]
            if ($log -notmatch ('LogDerivedDataCacheCommandlet: Display: Processing ' + [Regex]::Escape($package) + '(?:\s|$)')) {
                throw "Audio DDC pass $pass did not process $package."
            }
        }
        $built = @([Regex]::Matches($log, 'Building compressed audio format[^\r\n]*wave (SW_[^ .\r\n]+)') | ForEach-Object { $_.Groups[1].Value })
        if ($pass -eq 2 -and $built.Count) { throw 'Second audio DDC pass rebuilt compressed waves; cache reuse was not established.' }
        $passes += @{ pass = $pass; exit_code = 0; processed_sound_waves = $inventory.Count; compressed_waves_built = $built; engine_log = [IO.Path]::GetFileName($engineLog); engine_log_sha256 = (Get-FileHash -LiteralPath $engineLog -Algorithm SHA256).Hash.ToLowerInvariant() }
    }
    foreach ($item in $inventory) {
        $path = Join-Path (Join-Path $projectRoot 'Content') $item.path
        if ((Get-Item -LiteralPath $path).Length -ne $item.bytes -or (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant() -ne $item.sha256) {
            throw "Authored audio changed during warmup: $($item.path)."
        }
    }
    @{ version = 1; status = 'complete'; target_platforms = @('WindowsEditor', 'Windows'); sound_waves = $inventory; passes = $passes; audio_unchanged = $true; second_pass_compression_builds = 0; timestamp_utc = [DateTime]::UtcNow.ToString('o') } |
        ConvertTo-Json -Depth 8 | Set-Content -LiteralPath $receipt -Encoding utf8
} finally {
    Remove-Item -LiteralPath $collection -Force -ErrorAction SilentlyContinue
}
